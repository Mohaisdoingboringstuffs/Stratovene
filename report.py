"""Markdown report generator."""

from __future__ import annotations

from pathlib import Path

from enclosure import NodeSolution
from parameters import Parameter
from validation import DIAZ_LOBO, FU_2023


LIMITATIONS = """
- A ground lamp test is not a stratospheric flight test.
- A standard atmosphere is not an aircraft-specific atmosphere.
- Effective sky temperature is model-dependent (Dai-Fang 2014 broadband vs layered band model).
- Dai et al. 2016 publishes upward IR transmittance vs altitude; it does not give T_sky.
- AAO literature properties are not guaranteed for a fabricated STRATOVANE sample.
- Optical properties must eventually be measured on our sample (solar + IR spectral).
- Aircraft attitude and surrounding structure change view factors.
- Wind/air-speed changes convection strongly at low altitude and weakly at 20 km.
- Internal electronics heat load must eventually come from a real target system.
- Daytime and nighttime conditions must both be considered (over-cooling at night).
- 3 K is the CMB, not the stratospheric radiative environment.
- STRATOVANE is not flight-proven.
- Fu et al. 2023 is a nanoparticle-polymer airship experiment, not AAO-Al.
"""


def _param_table(params: list[Parameter] | list[dict]) -> str:
    lines = ["| parameter | value | unit | source | status | uncertainty |", "|---|---|---|---|---|---|"]
    for p in params:
        d = p.as_dict() if hasattr(p, "as_dict") else p
        lines.append(
            f"| {d.get('parameter', d.get('name'))} | {d.get('value')} | {d.get('unit')} | {d.get('source')} | {d.get('status')} | {d.get('uncertainty')} |"
        )
    return "\n".join(lines)


def write_report(
    path: Path,
    cfg_text: str,
    solutions: dict[str, NodeSolution],
    comparison_rows: list[dict],
    mc_text: str,
    sensitivity_text: str,
    next_experiment: str,
    validation_text: str,
    answers: str,
) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# STRATOVANE thermal model report",
        "",
        "This report is generated by the model. It does not claim flight heritage.",
        "",
        "## INPUTS AND ASSUMPTIONS",
        cfg_text,
        "",
        "## LITERATURE VALUES",
        f"- Díaz-Lobo benchmark: ΔT={DIAZ_LOBO['deltaT_C']} C, Pcool={DIAZ_LOBO['peak_cooling_W_m2']} W/m2, G={DIAZ_LOBO['irradiance_W_m2']} W/m2, T_amb={DIAZ_LOBO['ambient_C']} C, RH={DIAZ_LOBO['RH']}. {DIAZ_LOBO['source']}",
        f"- Fu et al. 2023 airship (different material): ~{FU_2023['deltaT_C']} C vs control. {FU_2023['source']}",
        "",
        "## MEASURED VALUES",
        "None from a STRATOVANE coupon are bundled. Replace `STRATOVANE_AAO_MEASURED` in the material database.",
        "",
        "## ATMOSPHERIC CONDITIONS",
        "T_air and (P, rho, mu, k) from U.S. Standard Atmosphere 1976. T_sky_effective is separate.",
        "",
        "## MATERIAL PROPERTIES",
    ]
    for name, sol in solutions.items():
        lines.append(f"### {name}")
        lines.append(_param_table(sol.ledger.items))
        lines.append("")
    lines += [
        "## THERMAL RESULTS",
        "| material | z_m | T_surf_C | T_wall_C | T_elec_C | Q_rad_out | Q_solar | Q_conv | P_cool_net | mass_kg | P_elec |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in comparison_rows:
        lines.append(
            f"| {r['material']} | {r['altitude_m']:.0f} | {r['T_surface_C']:.2f} | {r['T_wall_C']:.2f} | "
            f"{r['T_electronics_C']:.2f} | {r['Q_rad_out_W']:.2f} | {r['Q_solar_W']:.2f} | "
            f"{r['Q_conv_W']:.2f} | {r['Q_env_rejected_W']:.2f} | {r['mass_total_kg']:.4f} | {r['power_consumption_W']:.1f} |"
        )
    lines += [
        "",
        "No automatic winner is declared. Compare the numbers.",
        "",
        "## UNCERTAINTIES",
        mc_text,
        sensitivity_text,
        f"**Next measurement:** {next_experiment}",
        "",
        "## VALIDATION",
        validation_text,
        "",
        "## PRIMARY ENGINEERING QUESTIONS",
        answers,
        "",
        "## LIMITATIONS",
        LIMITATIONS,
        "",
        "## MEASUREMENTS STILL REQUIRED",
        "- Spectral solar reflectance of the fabricated STRATOVANE surface",
        "- Spectral IR emissivity (2-25 μm minimum) of the fabricated surface",
        "- Actual avionics heat load vs time",
        "- Enclosure installation view factors on the aircraft",
        "- Local airspeed at the enclosure",
        "- Downwelling IR or a validated RT code at flight altitude",
        "- Day/night temperature limits of the electronics",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
